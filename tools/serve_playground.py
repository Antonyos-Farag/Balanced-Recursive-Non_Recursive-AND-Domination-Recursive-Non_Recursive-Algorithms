"""Serve ``playground/index.html`` the way a proxy-hosted preview wants it.

    python -m tools.serve_playground            # http://0.0.0.0:8000
    python -m tools.serve_playground --port 8080 --bind 127.0.0.1

``python -m http.server --directory playground`` — the command the README used to
recommend — works, but it is a 1990s-shaped server with four habits that show up
the moment the page is loaded through a proxy or an iframe:

============  ===============================================================
HTTP/1.0      one connection per request; the proxy cannot keep a socket warm
backlog 5     a health check plus the page plus a favicon is already half of it
no charset    ``text/html`` without ``charset=utf-8``, on a page whose text is
              full of box-drawing characters and em dashes
no cache rule a proxy is free to serve yesterday's copy of a page you just
              regenerated
============  ===============================================================

This is the same idea with those four habits fixed, and nothing else: stdlib
only, no configuration, no dependencies.  It is deliberately not a web
framework -- it serves one directory of static files and it serves it politely.

The Python test suite starts this server on an ephemeral port and asserts the
four headers above plus a byte-for-byte body, so the claims in the class
docstring cannot rot (``tests/test_serve_playground.py``).
"""

from __future__ import annotations

import argparse
import socket
import sys
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from typing import Optional, Sequence

__all__ = ["PlaygroundHandler", "PlaygroundServer", "make_server", "main"]

#: Where the page lives, resolved from this file so the server works from any
#: working directory (the preview host starts processes wherever it likes).
PLAYGROUND = Path(__file__).resolve().parent.parent / "playground"

DEFAULT_BIND = "0.0.0.0"
DEFAULT_PORT = 8000


class PlaygroundHandler(SimpleHTTPRequestHandler):
    """Static files, with the four proxy-hostile defaults turned around."""

    #: HTTP/1.1 is what makes keep-alive legal; the base class then has to send
    #: an accurate ``Content-Length`` on every response, which it does.
    protocol_version = "HTTP/1.1"

    #: UTF-8 everywhere, and explicitly, so a browser never has to sniff.
    extensions_map = {
        **SimpleHTTPRequestHandler.extensions_map,
        "": "application/octet-stream",
        ".html": "text/html; charset=utf-8",
        ".css": "text/css; charset=utf-8",
        ".js": "text/javascript; charset=utf-8",
        ".json": "application/json; charset=utf-8",
        ".svg": "image/svg+xml",
        ".txt": "text/plain; charset=utf-8",
        ".md": "text/plain; charset=utf-8",
    }

    def end_headers(self) -> None:
        # The playground is regenerated by hand; a cached copy is always a bug.
        self.send_header("Cache-Control", "no-store, must-revalidate")
        self.send_header("X-Content-Type-Options", "nosniff")
        super().end_headers()

    def log_message(self, format: str, *args) -> None:  # noqa: A002 - stdlib's name
        """One short line per request, on stderr, where the preview log reads it.

        ``--quiet`` (or ``make_server(..., quiet=True)``, which is what the test
        suite uses) turns this off, so a burst of requests cannot bury the
        interesting lines in the preview's log pane.
        """
        if getattr(self.server, "quiet", False):
            return
        sys.stderr.write(f"{self.log_date_time_string()} {self.address_string()} {format % args}\n")


class PlaygroundServer(ThreadingHTTPServer):
    """A threaded server with a listen queue that can absorb a burst."""

    daemon_threads = True
    allow_reuse_address = True

    #: The stdlib default is 5.  A preview host is allowed to be impatient.
    request_queue_size = 128

    #: Set by ``make_server``/``--quiet``; read by the handler.
    quiet = False


def make_server(
    bind: str = DEFAULT_BIND,
    port: int = DEFAULT_PORT,
    directory: Optional[Path] = None,
    quiet: bool = False,
) -> PlaygroundServer:
    """Build (but do not start) a server for ``directory``.

    ``port=0`` asks the operating system for a free port, which is what the test
    suite does so that it can never collide with a running preview.  ``quiet``
    suppresses the one-line-per-request log.
    """
    root = Path(directory) if directory is not None else PLAYGROUND
    if not root.is_dir():
        raise SystemExit(f"no such directory: {root}")
    handler = partial(PlaygroundHandler, directory=str(root))
    server = PlaygroundServer((bind, port), handler)
    server.root = root  # type: ignore[attr-defined]  # handy in tests and logs
    server.quiet = quiet  # type: ignore[attr-defined]
    return server


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--bind", default=DEFAULT_BIND, help=f"address to bind (default {DEFAULT_BIND})")
    parser.add_argument("--port", type=int, default=DEFAULT_PORT, help=f"port (default {DEFAULT_PORT})")
    parser.add_argument(
        "--directory",
        type=Path,
        default=None,
        help=f"directory to serve (default {PLAYGROUND})",
    )
    parser.add_argument("--quiet", action="store_true", help="do not log every request")
    args = parser.parse_args(argv)

    try:
        server = make_server(args.bind, args.port, args.directory, quiet=args.quiet)
    except OSError as error:
        # The most likely cause by far is "something is already on that port",
        # and saying so is more useful than a traceback.
        print(f"cannot listen on {args.bind}:{args.port}: {error}", file=sys.stderr)
        return 1

    host, port = server.server_address[:2]
    shown = "localhost" if host in ("0.0.0.0", "::") else host
    family = socket.AF_INET6 if ":" in str(host) else socket.AF_INET
    print(f"serving {server.root} on http://{shown}:{port}/  ({family.name}, HTTP/1.1, no-store)")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nstopped")
    finally:
        server.server_close()
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
